#!/usr/bin/env python3
"""由 semantic/user_properties.yaml 產生用戶表 DDL（寬表：每個屬性一個實體欄位；新增屬性 = 改 YAML + ALTER ADD COLUMN，秒級）。

為什麼不用 JSON 欄位放 300 個屬性：實測 100k 列 × 300 屬性，寬表載入 2.8 s、JSON 16 s（組 JSON 與動態型別的成本），
磁碟相近、查詢相近；且 JSON 會把 100 存成 Int64、100.5 存成 Float64，型別子欄位讀取容易踩雷。未登記的零星屬性仍放 props_extra JSON。

用法：python3 backend/clickhouse/gen_users_ddl.py            # 印 Replicated 版 DDL
     python3 backend/clickhouse/gen_users_ddl.py --write    # 寫回 schema.sql 的標記區塊
     python3 backend/clickhouse/gen_users_ddl.py --local    # 單機版（測試）
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
BEGIN, END = "-- >>> generated by gen_users_ddl.py (do not edit) >>>", "-- <<< generated <<<"
TYPES = {"string": "String", "enum": "LowCardinality(String)", "number": "Nullable(Float64)", "bool": "UInt8", "date": "Nullable(Date)", "datetime": "Nullable(DateTime64(3, 'UTC'))"}
DICT_TYPES = {"string": "String", "enum": "String", "number": "Float64", "bool": "UInt8", "date": "Date", "datetime": "DateTime64(3)"}
MAX_HOT = 50


def load_props() -> list[dict]:
    return yaml.safe_load((ROOT / "semantic" / "user_properties.yaml").read_text(encoding="utf-8"))["user_properties"]


def columns(props: list[dict]) -> list[tuple[str, str, str]]:
    """(key, clickhouse type, yaml type)；L3 以上不進用戶寬表（留在 id_map／遮罩檢視），L4 本來就不在 YAML。"""
    return [(p["key"], TYPES[p["type"]], p["type"]) for p in props if p.get("sensitivity", "L1") in ("L0", "L1", "L2")]


def hot(props: list[dict]) -> list[tuple[str, str, str]]:
    h = [(p["key"], DICT_TYPES[p["type"]], p["type"]) for p in props if (p.get("filterable") or p.get("groupable")) and p.get("sensitivity", "L1") in ("L0", "L1", "L2")]
    return h[:MAX_HOT]


def ddl(local: bool = False) -> str:
    props = load_props(); cols = columns(props); hot_cols = hot(props)
    eng = (lambda name, ver: f"ReplacingMergeTree({ver})" if local else f"ReplicatedReplacingMergeTree('/ch/{{shard}}/dmp.{name}', '{{replica}}', {ver})")
    col_lines = ",\n".join(f"    {k:<20} {t}" for k, t, _ in cols)
    out = [BEGIN,
           "-- 用戶表（對應神策 Kudu 用戶表；docs/23 §4.1）：每個屬性一個實體欄位（由 user_properties.yaml 產生），未登記屬性放 props_extra。",
           "-- 更新分兩路：日批整份快照（users_snapshot → users，INSERT 不 UPDATE）；即時零星更新走 user_prop_log 每 10 分鐘微批合併。",
           "CREATE TABLE IF NOT EXISTS dmp.users_snapshot\n(\n    snapshot_date        Date,\n    one_id               String,\n    one_id_uint          UInt64 DEFAULT cityHash64(one_id),\n"
           + col_lines + ",\n    props_extra          JSON,\n    loaded_at            DateTime64(3, 'UTC') DEFAULT now64(3)\n)\n"
           + f"ENGINE = {eng('users_snapshot', 'loaded_at')}\nPARTITION BY toYYYYMM(snapshot_date)\nORDER BY (snapshot_date, one_id)\nTTL snapshot_date + INTERVAL 90 DAY;   -- 屬性歷史保留 90 天",
           "",
           "CREATE TABLE IF NOT EXISTS dmp.users\n(\n    one_id               String,\n    one_id_uint          UInt64 DEFAULT cityHash64(one_id),\n"
           + col_lines + ",\n    props_extra          JSON,\n    first_seen           DateTime64(3, 'UTC'),\n    updated_at           DateTime64(3, 'UTC')\n)\n"
           + f"ENGINE = {eng('users', 'updated_at')}\nORDER BY one_id;",
           "",
           "-- 即時零星更新（profile_set／set_once／increment／unset）：每屬性一列，微批合併進 users\nCREATE TABLE IF NOT EXISTS dmp.user_prop_log\n(\n    one_id   String,\n    prop     LowCardinality(String),\n    value    String,\n    op       LowCardinality(String),\n    ts       DateTime64(3, 'UTC'),\n    ingested_at DateTime DEFAULT now()\n)\n"
           + ("ENGINE = MergeTree" if local else "ENGINE = ReplicatedMergeTree('/ch/{shard}/dmp.user_prop_log', '{replica}')") + "\nPARTITION BY toYYYYMMDD(ts)\nORDER BY (one_id, prop, ts)\nTTL ingested_at + INTERVAL 30 DAY;   -- 以載入時間計：歷史檔的 profile_set 事件時間可能很舊",
           "",
           f"-- 事件查詢關聯用戶屬性：可篩選／可分組的熱欄位（≤ {MAX_HOT} 個）載成 dictionary，dictGet 不 JOIN；其餘屬性走 users FINAL JOIN\nCREATE DICTIONARY IF NOT EXISTS dmp.users_dict\n(\n    one_id_uint UInt64,\n"
           + ",\n".join(f"    {k:<20} {t}" for k, t, _ in hot_cols) + "\n)\nPRIMARY KEY one_id_uint\n"
           + "SOURCE(CLICKHOUSE(NAME dmp_dict QUERY 'SELECT one_id_uint, " + ", ".join(f"{('ifNull(' + k + ', 0)') if y == 'number' else ('ifNull(' + k + ', toDate(0))') if y == 'date' else k}" for k, _, y in hot_cols)
           + " FROM dmp.users FINAL'))\nLAYOUT(HASHED())\nLIFETIME(MIN 300 MAX 600);",
           END]
    return "\n".join(out)


def write_back() -> None:
    p = ROOT / "clickhouse" / "schema.sql"; s = p.read_text(encoding="utf-8")
    block = ddl()
    if BEGIN in s:
        s = re.sub(re.escape(BEGIN) + ".*?" + re.escape(END), lambda m: block, s, flags=re.S)
    else:
        s = s.replace("-- 維度表（docs/06 §7.2）", block + "\n\n-- 維度表（docs/06 §7.2）", 1)
    p.write_text(s, encoding="utf-8"); print(f"schema.sql updated: {len(columns(load_props()))} columns, {len(hot(load_props()))} hot")


if __name__ == "__main__":
    if "--write" in sys.argv:
        write_back()
    else:
        print(ddl(local="--local" in sys.argv))
